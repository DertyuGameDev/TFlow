export const normalizeCity = (value: string) => value.trim().toLocaleLowerCase("ru").replace(/ё/g, "е").replace(/[\s-]+/g, "");

export function cityMatches(query: string, cities: readonly string[], limit = 8): string[] {
  const term = normalizeCity(query);
  const alias = term === "спб" || term === "питер" ? "санктпетербург" : term === "мск" ? "москва" : term;
  const unique = Array.from(new Map(cities.map(city => [normalizeCity(city), city])).values());
  return unique.filter(city => normalizeCity(city).includes(alias)).sort((a, b) => {
    // Prefer a match at the start, keeping the initial popular-city order otherwise.
    return Number(normalizeCity(b).startsWith(alias)) - Number(normalizeCity(a).startsWith(alias));
  }).slice(0, limit);
}
